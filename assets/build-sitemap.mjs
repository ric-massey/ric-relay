/* Writes sitemap.xml — every public, indexable page, with the date it last
   changed in git.

       node assets/build-sitemap.mjs           write it
       node assets/build-sitemap.mjs --check   exit 1 if it is stale

   Nobody shares a home page: the pieces people pass around are a single
   explainer, a single game, a single room. A sitemap is how a search engine
   finds those without being walked in from the front door, so a page added
   and never linked from anywhere still gets found.

   The list is `git ls-files '*.html'` minus EXCLUDE, the same shape as
   assets/terminal/build-pages.mjs — but a sitemap answers a different
   question from the search box, so the two lists differ on purpose and the
   reasons are written against each rule below.

   NOT WIRED INTO THE CHECKS YET (2026-11-12). build-pages.mjs has a test that
   runs its --check, so a page added without a rerun goes red; this one has no
   such test, so sitemap.xml can silently go stale. Add `node
   assets/build-sitemap.mjs --check` to a suite in .github/checks.mjs before
   relying on it. Until then, rerun it by hand when a page is added or removed. */
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'sitemap.xml');
const SITE = 'https://' + readFileSync(join(ROOT, 'CNAME'), 'utf8').trim();

const EXCLUDE = [
  [/^(docs|\.github)\//, 'notes and tests about the site, not the site'],
  [/\/tests?\/|fixtures/, 'test pages'],
  [/^(admin|visitors|account|atlas)\//, "Ric's tools, behind their own sign-in"],
  [/^projects\/dads-race\//, 'HERMISCUS stays unpromoted (AGENTS.md)'],
  // The player pages carry <meta name="robots" content="noindex"> from
  // cards.py: they exist to be shared by the person in them, not to be found
  // by someone searching that person's name. Listing them here would ask for
  // exactly the indexing the noindex refuses.
  [/^projects\/cs\/p\//, 'one page per CS player — noindex by design'],
  // A redirect has nothing of its own to index, and 404.html is an error page.
  [/^(404|frontdoor|systems|updates)\.html$/, 'redirects and the 404'],
  [/^projects\/crossfire\//, 'a redirect to KONDRITE'],
  [/^projects\/climbing\/add(-route)?\.html$/, "Ric's logging forms"],
  [/^projects\/kondrite\/sounds\//, "Ric's listening booth"],
  /* The rooms that are unlisted because they are thin (AGENTS.md, "The menu
     system"). Keeping them out of the navs and then handing them to a search
     engine would be advertising the unfinished work the rule exists to not
     advertise. They stay reachable by URL and from the terminal.
     Measured 2026-11-12: VAL has 0 matches, Workbench has 1 card and an
     "Empty slot". Climbing Media is NOT here — it has 8 items (5 send clips,
     3 photos) and is listed. */
  [/^(val|workbench)\.html$/, 'unlisted because thin — not advertised to crawlers either'],
];

/* How often a page is worth re-reading, and how much of the site it is. Both
   are hints a crawler may ignore; they are here so the explainers and games —
   the pieces that are actually shared — are not ranked below a form. */
const WEIGHT = [
  [/^index\.html$/, 1.0, 'daily'],
  [/^(weather|weather-pro)\.html$/, 0.9, 'daily'],
  [/^projects\/(how-|spacetime\/|kondrite\/|offramp\/|farlight\/|starfield\/|siege-conductor\/)/, 0.9, 'monthly'],
  [/^(cs|gaming|captures|climbing|training|orrin|exploration|psyche|entertainment)\.html$/, 0.8, 'weekly'],
  [/^projects\//, 0.7, 'monthly'],
];

const href = (f) => '/' + f.replace(/(^|\/)index\.html$/, '$1');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

export function build() {
  const files = execFileSync('git', ['ls-files', '*.html'], { cwd: ROOT, encoding: 'utf8' })
    .split('\n').filter(Boolean).map((f) => f.replace(/\\/g, '/'))
    .filter((f) => !EXCLUDE.some(([re]) => re.test(f))).sort();

  const urls = files.map((f) => {
    /* The last commit that touched it. A working tree with uncommitted edits
       reports the committed date, which is the right answer: the sitemap
       describes what is published, and nothing uncommitted is. */
    const at = execFileSync('git', ['log', '-1', '--format=%cs', '--', f], { cwd: ROOT, encoding: 'utf8' }).trim();
    const [, priority, changefreq] = WEIGHT.find(([re]) => re.test(f)) || [, 0.6, 'monthly'];
    return { loc: SITE + href(f), at, priority, changefreq };
  });

  return '<?xml version="1.0" encoding="UTF-8"?>\n'
    + '<!-- Generated by assets/build-sitemap.mjs. Do not hand-edit: rerun it. -->\n'
    + '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
    + urls.map((u) => '  <url>\n'
      + `    <loc>${esc(u.loc)}</loc>\n`
      + (u.at ? `    <lastmod>${u.at}</lastmod>\n` : '')
      + `    <changefreq>${u.changefreq}</changefreq>\n`
      + `    <priority>${u.priority.toFixed(1)}</priority>\n`
      + '  </url>\n').join('')
    + '</urlset>\n';
}

const xml = build();
if (process.argv.includes('--check')) {
  let have = '';
  try { have = readFileSync(OUT, 'utf8'); } catch {}
  if (have !== xml) {
    console.error('sitemap.xml is stale — run `node assets/build-sitemap.mjs`');
    process.exit(1);
  }
  console.log(`sitemap.xml is current — ${(xml.match(/<url>/g) || []).length} pages`);
} else {
  writeFileSync(OUT, xml);
  console.log(`wrote /sitemap.xml — ${(xml.match(/<url>/g) || []).length} pages`);
}
