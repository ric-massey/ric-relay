/* Writes assets/terminal/pages.js — the terminal search's list of every public
   page, read off the pages themselves: <title>, <meta name=description> and
   the h1–h3 headings.

       node assets/terminal/build-pages.mjs           write it
       node assets/terminal/build-pages.mjs --check   exit 1 if it is stale

   Every tracked .html is in it unless EXCLUDE says why not, so a new page is
   searchable the day it lands. .github/test/terminal-search.mjs runs --check,
   so a page added, renamed or retitled without a rerun goes red. */
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'assets', 'terminal', 'pages.js');

const EXCLUDE = [
  [/^(docs|\.github)\//, 'notes and tests about the site, not the site'],
  [/\/tests?\/|fixtures/, 'test pages'],
  [/^(admin|visitors|account|atlas)\//, "Ric's tools, behind their own sign-in"],
  [/^projects\/dads-race\//, 'HERMISCUS stays unpromoted (AGENTS.md)'],
  [/^projects\/cs\/p\//, "one page per CS player — the players aren't the site"],
  [/^(404|frontdoor|systems|updates|terminal)\.html$/, 'redirects, the 404 and the terminal itself'],
  [/^projects\/crossfire\//, 'a redirect to KONDRITE'],
  [/^projects\/climbing\/add(-route)?\.html$/, "Ric's logging forms"],
  [/^projects\/kondrite\/sounds\//, "Ric's listening booth"],
];

// Which room a page belongs to, for in:<room>. Longest prefix wins.
const ROOM_OF = [
  ['projects/climbing/', 'climbing'], ['climbing.html', 'climbing'],
  ['projects/training/', 'training'], ['training.html', 'training'],
  ['projects/spacetime/', 'exploration'], ['projects/how-', 'exploration'], ['exploration.html', 'exploration'],
  ['projects/psyche/', 'mind'], ['projects/state-of-mind-line/', 'mind'], ['projects/autism-reflection.html', 'mind'], ['psyche.html', 'mind'],
  ['projects/kondrite/', 'gaming'], ['projects/farlight/', 'gaming'], ['projects/offramp/', 'gaming'], ['projects/starfield/', 'gaming'], ['gaming.html', 'gaming'],
  ['projects/siege-conductor/', 'workbench'], ['workbench.html', 'workbench'],
  ['entertainment', 'entertainment'], ['weather', 'weather'],
  ['captures.html', 'captures'], ['orrin.html', 'orrin'], ['cs.html', 'cs'], ['val.html', 'val'],
  ['log.html', 'log'], ['map.html', 'map'],
];

const decode = (s) => s
  .replace(/<[^>]+>/g, ' ')
  .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#39;|&apos;|&rsquo;/g, '’').replace(/&mdash;/g, '—').replace(/&ndash;/g, '–')
  .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n))
  .replace(/\s+/g, ' ').trim();

export function build() {
  const files = execFileSync('git', ['ls-files', '*.html'], { cwd: ROOT, encoding: 'utf8' })
    .split('\n').filter(Boolean).map((f) => f.replace(/\\/g, '/'))
    .filter((f) => !EXCLUDE.some(([re]) => re.test(f))).sort();
  const pages = files.map((href) => {
    const html = readFileSync(join(ROOT, href), 'utf8');
    // Inline scripts and styles hold strings that look like markup.
    const body = html.replace(/<script\b[\s\S]*?<\/script>/gi, '').replace(/<style\b[\s\S]*?<\/style>/gi, '');
    const title = decode((html.match(/<title>([\s\S]*?)<\/title>/i) || [, href])[1]);
    const desc = decode((html.match(/<meta\s+name=["']description["']\s+content=["']([^"']*)["']/i) || [, ''])[1]);
    const heads = [...new Set([...body.matchAll(/<h[1-3]\b[^>]*>([\s\S]*?)<\/h[1-3]>/gi)].map((m) => decode(m[1])).filter((h) => h && h.length < 90))].slice(0, 14);
    const room = (ROOM_OF.filter(([p]) => href.startsWith(p)).sort((a, b) => b[0].length - a[0].length)[0] || [])[1] || null;
    // "Stats — Climbing" shows as "Stats"; the rest is still searched.
    const [name, ...rest] = title.split(/\s+[—|–]\s+/);
    return { href, title: name || title, keys: rest.join(' · '), body: desc, text: heads.join(' · '), room };
  });
  return '/* Generated by assets/terminal/build-pages.mjs from the pages themselves —\n' +
    '   do not edit; rerun it when a page is added, renamed or retitled. */\n' +
    'window.TERMINAL_PAGES = ' + JSON.stringify(pages, null, 1) + ';\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = build();
  if (process.argv.includes('--check')) {
    let now = '';
    try { now = readFileSync(OUT, 'utf8'); } catch {}
    if (now.replace(/\r\n/g, '\n') !== text) { console.error('assets/terminal/pages.js is stale — run node assets/terminal/build-pages.mjs'); process.exit(1); }
    console.log('pages.js is current');
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT.replace(ROOT, '').replace(/\\/g, '/')} — ${JSON.parse(text.slice(text.indexOf('['), text.lastIndexOf(']') + 1)).length} pages`);
  }
}
