    args = sys.argv[1:]
    demo = '--demo' in args
    out = pathlib.Path('~/Desktop/HERMISCUS for Victoria').expanduser()
    if '--out' in args:
        out = pathlib.Path(args[args.index('--out') + 1]).expanduser()
    sources = [a for i, a in enumerate(args) if not a.startswith('--') and (i == 0 or args[i - 1] != '--out')]
    if len(sources) != 1:
        sys.exit(__doc__)
    if out.resolve().is_relative_to(ROOT.parent.parent) and not demo:
        sys.exit('build-open-site: the output holds the real key; write it outside the website repo.')

    html = strip_ric_blocks(read_source(sources[0]))
    if len(re.findall(r'<style[^>]*>', html)) != 1 or html.count(STATE) != 1:
        sys.exit('build-open-site: expected her file — one <style> and the STATE line.')

