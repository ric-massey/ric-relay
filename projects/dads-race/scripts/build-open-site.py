#!/usr/bin/env python3
"""Build Victoria's open website: her index.html, with Ric's extras riding inside it.

    python3 scripts/build-open-site.py ~/Downloads/hermesco-deploy.zip
    python3 scripts/build-open-site.py path/to/her/index.html [--out DIR] [--demo]

The result is ONE index.html she uploads in place of her own. It is her file — her screens,
her styles, her code, still one <style> and one inline <script> — with three changes:

  1. The top of her script (above the STATE line, where her database section lives) is
     Ric's database connection instead: the same project and key she already publishes,
     plus the offline queue. No sign-in — open the page and pick your name, as today. No
     demo. Her built-in copy of the race data is not carried over.
  2. Two lines in her code: start-up waits for Ric's layer (a no-op for everyone but Ric and
     Sydney), and the crew sheet says "18hr pace".
  3. Blocks marked data-ric at the end of <head> and <body>: Ric's Notes screen for
     everyone (shared/notes-layer.js + notes.css — Victoria asked for it), and Ric's
     race-day layer (shared/ric-layer.js + styles.css), which Ric and Sydney switch on from
     Settings ("Ric's race-day version"); it starts off, on Victoria's version.

When she edits the file and sends it back, scripts/import-original.py takes it as usual:
it drops everything above STATE and every data-ric block, so only her part is imported.

The output holds the real database key, so it is written OUTSIDE this repo (default
~/Desktop/HERMISCUS for Victoria/). --demo builds a keyless copy on the made-up race, for
testing without touching the live data.
"""
import json
import pathlib
import re
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHARED = ROOT / 'shared'
STATE = '/* ================= STATE ================= */'


def read_source(path):
    path = pathlib.Path(path).expanduser()
    if path.suffix == '.zip':
        with zipfile.ZipFile(path) as z:
            return z.read('index.html').decode('utf-8')
    return path.read_text(encoding='utf-8')


def strip_ric_blocks(html):
    """Remove the data-ric blocks a previous build put in, so a returned file rebuilds cleanly."""
    return re.sub(r'\s*<(style|script)\b[^>]*\bdata-ric(?=[\s>])[^>]*>.*?</\1>', '', html, flags=re.S)


def replace_once(text, old, new, what):
    if text.count(old) != 1:
        sys.exit(f'build-open-site: expected one {what}, found {text.count(old)}. Her file changed here.')
    return text.replace(old, new)


def real_config():
    local = (SHARED / 'config.local.js').read_text(encoding='utf-8')
    url = re.search(r"supabaseUrl:\s*'([^']+)'", local)
    key = re.search(r"publishableKey:\s*'([^']+)'", local)
    if not url or not key:
        sys.exit('build-open-site: shared/config.local.js has no database address/key.')
    if key.group(1).startswith('sb_secret') or '"role":"service_role"' in key.group(1):
        sys.exit('build-open-site: that is not a browser key. Refusing.')
    return url.group(1), key.group(1)


