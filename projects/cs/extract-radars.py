#!/usr/bin/env python3
"""Pull CS2's own radar maps out of the game, for the replays and kill snapshots.

    projects/cs/.cs-venv/Scripts/python projects/cs/extract-radars.py

The top-down radar every player sees in-game ships inside CS2's pak01_dir.vpk,
next to each map's calibration (resource/overviews/<map>.txt: where the image's
corner sits in world coordinates and how many units one pixel covers). This
uses Source 2 Viewer's command-line tool (tools/vrf/, gitignored — see
README.md) to unpack both, then writes:

    radar/<map>.webp          the radar, compressed for the web
    radar/<map>_lower.webp    the lower level, on Nuke, Train and Vertigo
    radar/radar.js            window.CS_RADAR = {map: {x, y, scale, split, …}}

Rerun after a CS2 update reworks a map. The art is Valve's.
"""

import json
import re
import subprocess
import sys
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
TOOLS = HERE / "tools"
VRF = TOOLS / "vrf" / "Source2Viewer-CLI.exe"
OUT = TOOLS / "out"
RADAR = HERE / "radar"


def vpk():
    acct = json.loads((HERE / "cs-account.json").read_text(encoding="utf-8"))
    return Path(acct["cs2_dir"]) / "game" / "csgo" / "pak01_dir.vpk"


def unpack():
    if not VRF.exists():
        raise SystemExit("Source 2 Viewer CLI isn't in tools/vrf/ — see README.md")
    for flt, extra in (("resource/overviews/", []), ("panorama/images/overheadmaps/", ["-e", "vtex_c", "-d"])):
        subprocess.run([str(VRF), "-i", str(vpk()), "-o", str(OUT), "-f", flt, *extra],
                       check=True, capture_output=True)


def kv(text):
    """The few values we need from a KeyValues overview file."""
    num = lambda k: (lambda m: float(m.group(1)) if m else None)(  # noqa: E731
        re.search(rf'"{k}"\s+"(-?[\d.]+)"', text))
    out = {"x": num("pos_x"), "y": num("pos_y"), "scale": num("scale")}
    lower = re.search(r'"lower".*?"AltitudeMax"\s+"(-?[\d.]+)"', text, re.S)
    if lower:
        out["split"] = float(lower.group(1))      # below this z, use the lower radar
    return out


def main():
    if "--skip-unpack" not in sys.argv:
        unpack()
    RADAR.mkdir(exist_ok=True)
    imgs = OUT / "panorama" / "images" / "overheadmaps"
    cal = {}
    for txt in sorted((OUT / "resource" / "overviews").glob("*.txt")):
        name = txt.stem
        if not re.match(r"^(de|cs)_[a-z0-9]+$", name):
            continue                               # skip arms race, night/variant copies
        src = imgs / f"{name}_radar_psd.png"
        if not src.exists():
            continue
        c = kv(txt.read_text(encoding="utf-8", errors="replace"))
        if None in (c["x"], c["y"], c["scale"]):
            continue
        Image.open(src).save(RADAR / f"{name}.webp", "WEBP", quality=82, method=6)
        c["img"] = f"radar/{name}.webp"
        low = imgs / f"{name}_lower_radar_psd.png"
        if low.exists() and "split" in c:
            Image.open(low).save(RADAR / f"{name}_lower.webp", "WEBP", quality=82, method=6)
            c["lower"] = f"radar/{name}_lower.webp"
        else:
            c.pop("split", None)
        cal[name] = c
    (RADAR / "radar.js").write_text(
        "// Generated by projects/cs/extract-radars.py from CS2's own overview files.\n"
        "// pixel = ((x - x0) / scale, (y0 - y) / scale) on a 1024px radar.\n"
        "window.CS_RADAR = " + json.dumps(cal, separators=(",", ":")) + ";\n",
        encoding="utf-8", newline="\n")
    print(f"radar: {len(cal)} maps -> {', '.join(cal)}")


if __name__ == "__main__":
    main()
