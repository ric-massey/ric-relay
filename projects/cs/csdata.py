"""Shared bits for the CS room's two writers.

`cs-data.js` is an accumulator, the same idea as the Apex room: every match that
has ever reached it stays, whichever source put it there. Leetify's list only
goes back so far and Valve's demos expire after a few weeks, so the file in this
repo is the one permanent record. Nothing in here ever deletes a match.

Identity rule: everyone in the lobby is shown by their in-game name, the way
Leetify and every other public stats site shows them (Ric's call, 2026-10-13).
Steam ids are never written, and share codes stay in local state.
"""

import json
import os
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA_JS = HERE / "cs-data.js"
MATCH_DIR = HERE / "matches"
ACCOUNT = HERE / "cs-account.json"
STATE = HERE / ".cs-state.json"     # local only: parsed demos, share codes
PREFIX = "window.CS_DATA = "

SHARE_DICT = "ABCDEFGHJKLMNOPQRSTUVWXYZabcdefhijkmnopqrstuvwxyz23456789"


def account():
    if not ACCOUNT.exists():
        raise SystemExit(
            f"{ACCOUNT.name} is missing — copy cs-account.example.json to it and "
            "put your SteamID64 in it.")
    acct = json.loads(ACCOUNT.read_text(encoding="utf-8"))
    acct["steam64"] = str(acct["steam64"]).strip()
    return acct


def read_state():
    try:
        return json.loads(STATE.read_text(encoding="utf-8"))
    except (FileNotFoundError, ValueError):
        return {}


def write_state(st):
    tmp = STATE.with_suffix(".tmp")
    tmp.write_text(json.dumps(st, indent=1), encoding="utf-8", newline="\n")
    os.replace(tmp, STATE)


def load():
    if not DATA_JS.exists():
        return {"matches": []}
    text = DATA_JS.read_text(encoding="utf-8")
    text = text[text.index(PREFIX) + len(PREFIX):].strip()
    return json.loads(text.rstrip(";"))


def save(data):
    data["matches"].sort(key=lambda m: m.get("at") or "", reverse=True)
    body = json.dumps(data, separators=(",", ":"), ensure_ascii=False)
    tmp = DATA_JS.with_suffix(".tmp")
    tmp.write_text(
        "// Generated by projects/cs/pull-leetify.py and parse-demos.py. Do not hand-edit:\n"
        "// both scripts merge into this file and never remove a match from it.\n"
        + PREFIX + body + ";\n", encoding="utf-8", newline="\n")
    os.replace(tmp, DATA_JS)


# ── replay tracks, packed ──
# Positions are most of a replay file. Packed, each player's track is the first
# sample after spawning (or after a gap) as a position, then each next sample as
# the step from the one before, with x and y in units of TRACK_Q (2 game units,
# under half a radar pixel). A track stops at its last sample instead of
# carrying nulls to the end of the round; `samples` says how long it was. About
# 30% smaller on disk and over the wire. cs.html's unpackTracks() undoes it, and
# projects/cs/test/parity.mjs holds the two to the same answer.
TRACK_Q = 2


def pack_tracks(replay):
    if replay.get("tracks_q"):
        return replay
    st = replay["stride"]
    for r in replay["rounds"]:
        n, packed = 0, {}
        for seat, tr in r["tracks"].items():
            n = max(n, len(tr) // st)
            out, prev = [], None
            for i in range(0, len(tr), st):
                p = tr[i:i + st]
                if p[0] is None:
                    out += [None] * st
                    prev = None
                    continue
                p = [round(p[0] / TRACK_Q), round(p[1] / TRACK_Q)] + list(p[2:])
                out += p if prev is None else [a - b for a, b in zip(p, prev)]
                prev = p
            while out and out[-1] is None:
                out.pop()
            packed[seat] = out
        r["samples"] = n
        r["tracks"] = packed
    replay["tracks_q"] = TRACK_Q
    return replay


def unpack_tracks(replay):
    q = replay.get("tracks_q")
    if not q:
        return replay
    st = replay["stride"]
    for r in replay["rounds"]:
        full = {}
        for seat, tr in r["tracks"].items():
            out, prev = [], None
            for i in range(0, len(tr), st):
                d = tr[i:i + st]
                if d[0] is None:
                    out += [None] * st
                    prev = None
                    continue
                prev = d if prev is None else [a + b for a, b in zip(prev, d)]
                out += [prev[0] * q, prev[1] * q] + prev[2:]
            out += [None] * (r["samples"] * st - len(out))
            full[seat] = out
        r["tracks"] = full
        del r["samples"]
    del replay["tracks_q"]
    return replay


def share_code_match_id(code):
    """A match share code (CSGO-xxxxx-…) packs Valve's match id, outcome id and
    a token. The match id is also in the filename of the demo CS2 downloads, so
    it is the key that lets a demo find the Leetify row for the same game."""
    if not code or not code.startswith("CSGO-"):
        return None
    n = 0
    for c in reversed(code[5:].replace("-", "")):
        if c not in SHARE_DICT:
            return None
        n = n * 57 + SHARE_DICT.index(c)
    raw = n.to_bytes(18, "big")
    return str(int.from_bytes(raw[0:8], "little"))


def share_code_ids(code):
    """(match id, reservation id) from a share code."""
    if not code or not code.startswith("CSGO-"):
        return None, None
    n = 0
    for c in reversed(code[5:].replace("-", "")):
        if c not in SHARE_DICT:
            return None, None
        n = n * 57 + SHARE_DICT.index(c)
    raw = n.to_bytes(18, "big")
    return str(int.from_bytes(raw[0:8], "little")), str(int.from_bytes(raw[8:16], "little"))


def demo_match_id(path):
    """Valve names a demo match730_<reservation id>_<…> — the share code's
    SECOND number, not the match id. Map it back through the share codes we
    know; fall back to the number itself."""
    m = re.match(r"match730_0*(\d+)_", Path(path).name)
    if not m:
        return None
    num = m.group(1)
    for code in read_state().get("codes", {}).values():
        mid, rid = share_code_ids(code)
        if num in (mid, rid):
            return mid
    return num


def find(data, *, valve_id=None, leetify_id=None, fingerprint=None):
    for m in data["matches"]:
        if valve_id and m.get("valve_id") == valve_id:
            return m
        if leetify_id and m.get("leetify_id") == leetify_id:
            return m
    if fingerprint:
        for m in data["matches"]:
            if fingerprint_of(m) == fingerprint:
                return m
    return None


def fingerprint_of(m):
    """Map, final score and Ric's K/D. Two different games agreeing on all of
    that is unlikely enough to merge on when no id lines up."""
    me = m.get("me") or {}
    if not m.get("map") or not m.get("score"):
        return None
    return (m["map"], tuple(m["score"]), me.get("k"), me.get("d"))


def result(us, them):
    return "W" if us > them else "L" if us < them else "T"
