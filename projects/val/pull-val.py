#!/usr/bin/env python3
"""Pull Ric's VALORANT matches from his own running Riot Client.

    python projects/val/pull-val.py              # new matches only
    python projects/val/pull-val.py --rebuild    # re-process every saved match

For every match in his history it hasn't seen, it fetches Riot's full match
details, keeps the raw answer locally in raw/ (gitignored — it carries every
player's account id), and writes:

  * val-data.js           every match's summary, rank, maps — what the page lists
  * matches/<id>.js       the match in full, round by round: every fight with
                          where all ten players stood and which way they faced,
                          the damage each player did to each other player
                          (head/body/legs), money and loadouts, the spike

val-data.js only grows: Riot's history is finite and this is the record.

Other players appear by agent, not by Riot ID — VALORANT stat sites only show
players who opted in, so the room does the same. `show_others_names` in
val-account.json flips that, if Ric decides otherwise.
"""

import hashlib
import json
import sys
import time
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import riot  # noqa: E402
from content import Content, metres, to_minimap  # noqa: E402

DATA_JS = HERE / "val-data.js"
MATCH_DIR = HERE / "matches"
RAW = HERE / "raw"
STATE = HERE / ".val-state.json"
ACCOUNT = HERE / "val-account.json"
PREFIX = "window.VAL_DATA = "
SKIP_QUEUES = {"deathmatch", "ggteam", "hurm", "newmap", "onefa", "snowball"}
HALF = {"swiftplay": 4, "spikerush": 3}
TRADE_S = 5


# ── files ─────────────────────────────────────────────────────
def read_json(p, default):
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (FileNotFoundError, ValueError):
        return default


def write(p, text):
    tmp = p.with_suffix(p.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8", newline="\n")
    tmp.replace(p)


def load_data():
    try:
        t = DATA_JS.read_text(encoding="utf-8")
        return json.loads(t[t.index(PREFIX) + len(PREFIX):].strip().rstrip(";"))
    except FileNotFoundError:
        return {"matches": []}
    except ValueError as e:
        # Not an empty archive: an unreadable one. Writing over it would keep
        # only the new matches, and .val-state.json would never re-add the old
        # ones — "the archive only grows" (bug sweep B6-5). Stop instead.
        raise SystemExit(f"val: {DATA_JS.name} could not be read ({e.__class__.__name__}) — "
                         "fix it (a merge conflict?) before pulling again. Nothing was written.")


def save_data(d):
    d["matches"].sort(key=lambda m: m.get("at") or "", reverse=True)
    write(DATA_JS, "// Generated by projects/val/pull-val.py. Never hand-edit; it only ever grows.\n"
          + PREFIX + json.dumps(d, separators=(",", ":"), ensure_ascii=False) + ";\n")


# ── one match ─────────────────────────────────────────────────
def process(raw, me, C, show_names):
    info = raw["matchInfo"]
    queue = info.get("queueID") or info.get("queueId") or ""
    rounds = raw.get("roundResults") or []
    if queue in SKIP_QUEUES or not rounds:
        return None, None
    players = raw["players"]
    by_id = {p["subject"]: p for p in players}
    mine = by_id.get(me)
    if not mine:
        return None, None
    my_team = mine["teamId"]
    mp = C.map(info["mapId"]) or {"name": info["mapId"].rsplit("/", 1)[-1]}

    # seats: Ric 0, his team, then the other team; fixed for the whole match
    order = [me] + sorted(p["subject"] for p in players if p["teamId"] == my_team and p["subject"] != me) \
        + sorted(p["subject"] for p in players if p["teamId"] != my_team)
    seat = {s: i for i, s in enumerate(order)}
    us = {s for s in order if by_id[s]["teamId"] == my_team}

    def label(s):
        p = by_id.get(s)
        if not p:
            return None
        if s == me or show_names:
            return f"{p.get('gameName')}#{p.get('tagLine')}" if p.get("gameName") else None
        return None

    seats = [{"seat": seat[s], "agent": C.agent(by_id[s].get("characterId")), "us": s in us,
              "me": s == me, "name": label(s), "tier": C.tier(by_id[s].get("competitiveTier"))}
             for s in order]

    # who attacks when: Red attacks first; halves swap; overtime swaps every round
    H = HALF.get(queue, 12)

    def attackers(r):
        if r < H:
            return "Red"
        if r < 2 * H:
            return "Blue"
        return "Red" if (r - 2 * H) % 2 == 0 else "Blue"
    # Trust the spike over the rule if they ever disagree (custom/odd modes).
    planted = [(r["roundNum"], by_id.get(r.get("bombPlanter"), {}).get("teamId"))
               for r in rounds if r.get("bombPlanter")]
    if planted and sum(t == attackers(n) for n, t in planted) < len(planted) / 2:
        _a = attackers
        attackers = lambda r: "Blue" if _a(r) == "Red" else "Red"  # noqa: E731

    def item(fd, killer):
        kind = (fd or {}).get("damageType")
        it = (fd or {}).get("damageItem")
        if kind == "Weapon":
            return C.item(it) or "Weapon"
        if kind == "Ability":
            return C.ability(by_id.get(killer, {}).get("characterId"), it) or "Ability"
        return {"Bomb": "Spike", "Melee": "Melee", "Fall": "Fall"}.get(kind, kind or "?")

    def at(loc, view=None):
        """Exact game coordinates, the same point on the minimap image (u, v
        as 0-1 of its width and height), facing, and the nearest callout."""
        if not loc:
            return None
        out = {"x": round(loc["x"]), "y": round(loc["y"]),
               "view": round(view, 2) if view is not None else None,
               "place": C.place(info["mapId"], loc["x"], loc["y"])}
        if mp.get("xm") is not None:
            u, v = to_minimap(mp, loc["x"], loc["y"])
            out["u"], out["v"] = round(u, 4), round(v, 4)
        return out

    totals = defaultdict(Counter)
    out_rounds = []
    for r in sorted(rounds, key=lambda r: r["roundNum"]):
        n = r["roundNum"]
        atk = attackers(n)
        my_side = "ATK" if my_team == atk else "DEF"
        won = r.get("winningTeam") == my_team
        stats = {ps["subject"]: ps for ps in r.get("playerStats") or []}

        # damage: who hit whom, where
        dmg = []
        for s, ps in stats.items():
            for d in ps.get("damage") or []:
                dmg.append({"from": seat.get(s), "to": seat.get(d.get("receiver")), "dmg": d.get("damage", 0),
                            "head": d.get("headshots", 0), "body": d.get("bodyshots", 0), "legs": d.get("legshots", 0)})
                if (s in us) != (d.get("receiver") in us):
                    totals[s]["dmg"] += d.get("damage", 0)
                    totals[s]["head"] += d.get("headshots", 0)
                    totals[s]["body"] += d.get("bodyshots", 0)
                    totals[s]["legs"] += d.get("legshots", 0)

        kills = sorted((k for ps in stats.values() for k in ps.get("kills") or []),
                       key=lambda k: k.get("roundTime", 0))
        alive = {"us": sum(1 for s in order if s in us), "them": sum(1 for s in order if s not in us)}
        fights, died, killed, assisted = [], set(), Counter(), set()
        for i, k in enumerate(kills):
            kr, vc = k.get("killer"), k.get("victim")
            t = round(k.get("roundTime", 0) / 1000, 2)
            locs = {pl["subject"]: pl for pl in k.get("playerLocations") or []}
            before = [alive["us"], alive["them"]]
            side = "us" if vc in us else "them"
            # Dying a second time means they were revived in between, so they
            # were counted dead once too often (bug sweep B6-6).
            if vc in died:
                alive[side] += 1
                before = [alive["us"], alive["them"]]
            alive[side] -= 1
            died.add(vc)
            if kr and kr != vc and (kr in us) != (vc in us):
                killed[kr] += 1
            for a in k.get("assistants") or []:
                assisted.add(a)
            k_at = at((locs.get(kr) or {}).get("location"), (locs.get(kr) or {}).get("viewRadians"))
            v_at = at(k.get("victimLocation"))
            traded = next((round(e.get("roundTime", 0) / 1000, 2) for e in kills[i + 1:]
                           if e.get("victim") == kr and e.get("roundTime", 0) - k.get("roundTime", 0) <= TRADE_S * 1000), None)
            fd = k.get("finishingDamage") or {}
            fights.append({
                "t": t, "killer": seat.get(kr), "victim": seat.get(vc),
                "assisters": [seat.get(a) for a in k.get("assistants") or []],
                "weapon": item(fd, kr), "kind": fd.get("damageType"), "alt_fire": fd.get("isSecondaryFireMode"),
                "killer_at": k_at, "victim_at": v_at, "distance_m": metres(k_at, v_at),
                "alive_before": before, "opening": i == 0, "traded_after": traded,
                "exchange": [d for d in dmg if {d["from"], d["to"]} == {seat.get(kr), seat.get(vc)}],
                "snapshot": [{"seat": seat.get(s), **(at(pl.get("location"), pl.get("viewRadians")) or {})}
                             for s, pl in locs.items() if s in seat]
                            + ([{"seat": seat.get(vc), **v_at, "dead": True}] if v_at and vc not in locs else []),
            })

        # KAST and multis, for everyone
        for s in order:
            traded = any(f["victim"] == seat[s] and f["traded_after"] is not None for f in fights)
            if killed[s] or s in assisted or s not in died or traded:
                totals[s]["kast"] += 1
            if killed[s] >= 2:
                totals[s][f"{min(killed[s], 5)}k"] += 1
        if kills:
            totals[kills[0].get("killer")]["fb"] += 1
            totals[kills[0].get("victim")]["fd"] += 1

        econ = {}
        for s, ps in stats.items():
            e = ps.get("economy") or {}
            econ[str(seat.get(s))] = {"loadout": e.get("loadoutValue"), "spent": e.get("spent"),
                                      "left": e.get("remaining"), "weapon": C.item(e.get("weapon")),
                                      "armor": C.item(e.get("armor"))}
            totals[s]["spent"] += e.get("spent") or 0
            totals[s]["loadout"] += e.get("loadoutValue") or 0
        spike = {}
        if r.get("bombPlanter"):
            spike["plant"] = {"t": round((r.get("plantRoundTime") or 0) / 1000, 2), "by": seat.get(r["bombPlanter"]),
                              "site": r.get("plantSite"), "at": at(r.get("plantLocation")),
                              "players": [{"seat": seat.get(p["subject"]), **(at(p.get("location"), p.get("viewRadians")) or {})}
                                          for p in r.get("plantPlayerLocations") or [] if p.get("subject") in seat]}
            totals[r["bombPlanter"]]["plants"] += 1
        if r.get("bombDefuser"):
            spike["defuse"] = {"t": round((r.get("defuseRoundTime") or 0) / 1000, 2), "by": seat.get(r["bombDefuser"]),
                               "at": at(r.get("defuseLocation")),
                               "players": [{"seat": seat.get(p["subject"]), **(at(p.get("location"), p.get("viewRadians")) or {})}
                                           for p in r.get("defusePlayerLocations") or [] if p.get("subject") in seat]}
            totals[r["bombDefuser"]]["defuses"] += 1

        out_rounds.append({
            "n": n + 1, "side": my_side, "w": won, "result": r.get("roundResult"),
            "ceremony": (r.get("roundCeremony") or "").replace("Ceremony", "") or None,
            "fights": fights, "damage": dmg, "economy": econ, "spike": spike or None,
            "my_kills": killed[me], "died": me in died,
            "scores": {str(seat.get(ps["subject"])): ps.get("score") for ps in stats.values()},
        })

    n_rounds = len(out_rounds)
    teams = {t["teamId"]: t for t in raw.get("teams") or []}
    us_won = (teams.get(my_team) or {}).get("roundsWon", sum(r["w"] for r in out_rounds))
    them_won = sum((t.get("roundsWon") or 0) for k, t in teams.items() if k != my_team) \
        or sum(not r["w"] for r in out_rounds)

    def line(s):
        p, t = by_id[s], totals[s]
        st = p.get("stats") or {}
        rp = st.get("roundsPlayed") or n_rounds or 1
        hits = t["head"] + t["body"] + t["legs"]
        return {"k": st.get("kills"), "d": st.get("deaths"), "a": st.get("assists"),
                "acs": round((st.get("score") or 0) / rp), "adr": round(t["dmg"] / rp, 1),
                "hs": round(100 * t["head"] / hits, 1) if hits else None,
                "fb": t["fb"], "fd": t["fd"], "kast": round(100 * t["kast"] / rp, 1),
                "plants": t["plants"], "defuses": t["defuses"]}

    me_line = line(me)
    st = mine.get("stats") or {}
    me_line.update({
        "agent": C.agent(mine.get("characterId")),
        "tier": C.tier(mine.get("competitiveTier")),
        "multi": {k: totals[me][k] for k in ("2k", "3k", "4k", "5k")},
        "shots": {"head": totals[me]["head"], "body": totals[me]["body"], "legs": totals[me]["legs"]},
        "avg_loadout": round(totals[me]["loadout"] / n_rounds) if n_rounds else None,
        "spent": totals[me]["spent"],
        "abilities": (st.get("abilityCasts") or {}),
        "dmg_received": round(sum(d["dmg"] for r in out_rounds for d in r["damage"] if d["to"] == 0) / n_rounds, 1),
    })
    board = [{**seats[seat[s]], **line(s)} for s in order]

    start = info.get("gameStartMillis")
    summary = {
        "id": public_id(info["matchId"]),
        "at": datetime.fromtimestamp(start / 1000, timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ") if start else None,
        "map": mp["name"], "map_url": info["mapId"], "queue": queue, "ranked": bool(info.get("isRanked")),
        "minutes": round((info.get("gameLengthMillis") or 0) / 60000),
        "score": [us_won, them_won], "result": "W" if us_won > them_won else "L" if us_won < them_won else "T",
        "start_side": out_rounds[0]["side"] if out_rounds else None,
        "me": me_line,
        "rounds": [{"w": r["w"], "side": r["side"], "k": r["my_kills"], "dead": r["died"],
                    "how": r["result"]} for r in out_rounds],
        "board": board,
    }
    detail = {"id": public_id(info["matchId"]), "map": mp["name"],
              "minimap": C.minimap(info["mapId"]),
              # u = y*xm + xa, v = x*ym + ya  (Valorant swaps the axes)
              "transform": {k: mp.get(k) for k in ("xm", "ym", "xa", "ya")},
              "callouts": [{**c_, **dict(zip(("u", "v"), (round(z, 4) for z in to_minimap(mp, c_["x"], c_["y"]))))}
                           for c_ in mp.get("callouts", [])] if mp.get("xm") is not None else [],
              "seats": seats, "rounds": out_rounds}
    return summary, detail


def public_id(match_id):
    """The id the site publishes. Not Riot's own: that one opens Riot's full
    record of the match — every player's Riot ID — to anyone with an account,
    which is what show_others_names: false promises not to publish. Riot's id
    stays in raw/ and .val-state.json."""
    return hashlib.sha256(("val:" + str(match_id)).encode()).hexdigest()[:16]


def write_detail(d):
    MATCH_DIR.mkdir(exist_ok=True)
    write(MATCH_DIR / f"{d['id']}.js",
          "// Generated by projects/val/pull-val.py from Riot's match details.\n"
          f"(window.VAL_MATCH=window.VAL_MATCH||{{}})[{json.dumps(d['id'])}]="
          + json.dumps(d, separators=(",", ":"), ensure_ascii=False) + ";\n")


def merge(data, summary, rr=None):
    data["matches"] = [m for m in data["matches"] if m["id"] != summary["id"]] + [summary]
    if rr:
        summary["rr"] = rr


# ── main ──────────────────────────────────────────────────────
def main():
    acct = read_json(ACCOUNT, {})
    show = bool(acct.get("show_others_names"))
    st = read_json(STATE, {})
    data = load_data()
    C = Content()
    RAW.mkdir(exist_ok=True)

    if "--rebuild" in sys.argv:
        for p in sorted(RAW.glob("*.json")):
            s, d = process(json.loads(p.read_text(encoding="utf-8")), st["puuid"], C, show)
            if s:
                merge(data, s, (st.get("rr") or {}).get(p.stem))
                write_detail(d)
        save_data(data)
        print(f"val: rebuilt {len(data['matches'])} matches from raw/")
        return

    try:
        S = riot.session()
    except riot.NotRunning as e:
        print(f"val: {e} — nothing pulled")
        return
    st["puuid"] = S.puuid
    data["player"] = acct.get("riot_id") or data.get("player")

    # the whole history Riot will give, 20 at a time
    ids, start = [], 0
    while True:
        h = S.history(start, start + 20)
        batch = h.get("History") or []
        ids += [(x["MatchID"], x.get("QueueID")) for x in batch]
        start += 20
        if not batch or start >= (h.get("Total") or 0):
            break
        time.sleep(0.5)

    # rank, and the RR each competitive match moved it by
    try:
        upd = S.get(f"/mmr/v1/players/{S.puuid}/competitiveupdates?startIndex=0&endIndex=20&queue=competitive")
        rr = st.setdefault("rr", {})
        for u in upd.get("Matches") or []:
            rr[u["MatchID"]] = {"earned": u.get("RankedRatingEarned"), "after": u.get("RankedRatingAfterUpdate"),
                                "tier": C.tier(u.get("TierAfterUpdate"))}
        latest = (upd.get("Matches") or [{}])[0]
        if latest.get("TierAfterUpdate") is not None:
            data["rank"] = {"tier": C.tier(latest["TierAfterUpdate"]), "rr": latest.get("RankedRatingAfterUpdate"),
                            "read": datetime.now().strftime("%Y-%m-%d")}
    except Exception as e:
        print(f"val: rank unavailable ({e.__class__.__name__})")

    seen = set(st.get("seen", []))
    new = 0
    for mid, queue in ids:
        if mid in seen:
            continue
        rawp = RAW / f"{mid}.json"
        try:
            if rawp.exists():
                raw = json.loads(rawp.read_text(encoding="utf-8"))
            else:
                raw = S.match(mid)
                write(rawp, json.dumps(raw))
                time.sleep(0.7)
            s, d = process(raw, S.puuid, C, show)
        except Exception as e:
            print(f"val: {mid} failed — {e}")
            continue
        seen.add(mid)
        if s:
            merge(data, s, (st.get("rr") or {}).get(mid))
            write_detail(d)
            new += 1
    # A match pulled before Riot listed its rank update gets it now that the
    # update is in the state; only --rebuild used to attach it (bug sweep B6-8).
    late = {public_id(k): v for k, v in (st.get("rr") or {}).items()}
    for m in data["matches"]:
        if not m.get("rr") and m["id"] in late:
            m["rr"] = late[m["id"]]
    st["seen"] = sorted(seen)
    write(STATE, json.dumps(st, indent=1))
    save_data(data)
    print(f"val: {len(ids)} in Riot's history, {new} new — {len(data['matches'])} in the archive")


if __name__ == "__main__":
    main()
